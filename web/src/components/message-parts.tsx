import type { MessageDetail } from '@/lib/api.ts';
import { Fact, Facts } from '@/system';

const people = (list: MessageDetail['to']) => list.map((p) => p.address).join(', ');

/** A message's text as far as sift holds it, under who it went to. Who sent it and when are in the panel's header. */
export function MessageBody({ detail }: { detail: MessageDetail }) {
  return (
    <article className="flex min-w-0 flex-col gap-5">
      {detail.to.length > 0 || detail.cc.length > 0 ? (
        <p className="text-muted-foreground">
          {detail.to.length > 0 ? `To ${people(detail.to)}` : ''}
          {detail.cc.length > 0 ? `${detail.to.length > 0 ? ', cc ' : 'Cc '}${people(detail.cc)}` : ''}
        </p>
      ) : null}
      {detail.body === null ? (
        <p className="text-muted-foreground">
          sift does not hold this message’s text. It keeps it only while the message waits on you, and for good once you have answered for it.
        </p>
      ) : detail.body === '' ? (
        <p className="text-muted-foreground">This message has no readable text, or is no longer in Gmail.</p>
      ) : (
        <div className="max-w-[68ch] text-reading leading-relaxed break-words whitespace-pre-wrap">{detail.body}</div>
      )}
    </article>
  );
}

const PASSED = { pass: 'passed', fail: 'failed', none: 'not checked' } as const;
const UNSUBSCRIBE = {
  available: 'One click; sift can do it',
  done: 'sift has unsubscribed you',
  manual: 'A link sift will not follow',
  none: null,
} as const;

/** The signals sift read in a message, the ones that weigh in a decision, in plain words. Leaves out what says nothing. */
export function SignalFacts({ detail }: { detail: MessageDetail }) {
  const f = detail.facts;
  const sentBy = [
    f.bulkService ? `bulk mail through ${f.bulkService}` : f.markedBulk ? 'marked as bulk mail' : null,
    f.autoGenerated ? 'sent automatically' : null,
  ].filter(Boolean);
  return (
    <Facts>
      <Fact term="Sender proved">{f.dmarc === 'pass' ? 'Yes (DMARC passed)' : `No (DMARC ${PASSED[f.dmarc]})`}</Fact>
      <Fact term="Addressed">{f.addressed === 'to' ? 'To you' : f.addressed === 'cc' ? 'Copied to you' : 'Not to you by name'}</Fact>
      {sentBy.length > 0 ? <Fact term="Sent as">{sentBy.join(', ')}</Fact> : null}
      {f.listId ? <Fact term="List">{f.listId}</Fact> : null}
      {UNSUBSCRIBE[detail.unsubscribe] ? <Fact term="Unsubscribe">{UNSUBSCRIBE[detail.unsubscribe]}</Fact> : null}
      {f.replyToDiffers ? <Fact term="Reply-to">Goes somewhere other than the sender</Fact> : null}
      {f.trackingPixel || f.trackedLinks ? (
        <Fact term="Tracking">{[f.trackingPixel ? 'a tracking pixel' : null, f.trackedLinks ? 'tracked links' : null].filter(Boolean).join(', ')}</Fact>
      ) : null}
      {f.isReply ? <Fact term="Thread">A reply{f.ownerInThread ? ' in a thread you wrote in' : ''}</Fact> : null}
    </Facts>
  );
}
