import { z } from 'zod';
import type { Confidential } from '../../confidential.ts';
import type { Facts } from '../../triage/facts.ts';
import { DecisionRow } from './activity.ts';
import { address, held } from './parts.ts';
import { SenderProfile } from './senders.ts';

const authentication = z.enum(['pass', 'fail', 'none']);

/** What Mild checked about one message: `Facts` (src/triage/facts.ts, which says what each means), checked against it. */
const MessageFactSet = z.object({
  unsubscribe: z.enum(['none', 'header', 'one-click']),
  listId: held.nullable(),
  markedBulk: z.boolean(),
  autoGenerated: z.boolean(),
  dmarc: authentication,
  spf: authentication,
  dkim: authentication,
  bulkService: z.string().nullable(),
  replyToDiffers: z.boolean(),
  addressed: z.enum(['to', 'cc', 'neither']),
  isReply: z.boolean(),
  category: z.enum(['personal', 'social', 'promotions', 'updates', 'forums']).nullable(),
  /** Absent for mail recorded before Mild read it. */
  important: z.boolean().optional(),
  /** These five are known only once a model has been asked about the message; the last four only for mail with HTML. */
  hasAttachments: z.boolean().optional(),
  trackingPixel: z.boolean().optional(),
  linkHosts: z.number().optional(),
  trackedLinks: z.boolean().optional(),
  linksOffDomain: z.boolean().optional(),
  /** Known only for a reply a model has been asked about. */
  earlierInThread: z.number().optional(),
  ownerInThread: z.boolean().optional(),
}) satisfies z.ZodType<Omit<Facts, 'listId'> & { listId: Confidential | null }>;
type MessageFactSet = z.infer<typeof MessageFactSet>;

/** A file a message carries, by its part. Its name came in the mail. */
export const MessageAttachment = z.object({ part: z.string(), name: held, type: held, size: z.int() });
export type MessageAttachment = z.infer<typeof MessageAttachment>;

/** One of Mild's digests, as the reader shows it in place of the message Mild wrote (`digestShown`, src/store/digests.ts). */
const DigestShown = z.object({
  labelId: z.string(),
  labelName: z.string(),
  since: z.number(),
  until: z.number(),
  /** What the model thought worth a look, and why in a line, by the message's id. */
  picks: z.array(z.object({ messageId: z.string(), why: held })),
  /** What it lists now, newest first: mail answered for or put back since has left it. */
  mail: z.array(z.object({ accountId: z.string(), messageId: z.string(), from: address, subject: held, receivedAt: z.number(), archivedAt: z.number() })),
});

export const MessageDetail = z.object({
  accountId: z.string(),
  messageId: z.string(),
  fromAddress: held,
  fromName: held.nullable(),
  to: z.array(address),
  cc: z.array(address),
  subject: held,
  receivedAt: z.number(),
  /** Triage headers as synced. */
  headers: z.record(z.string(), held),
  /**
   * The readable text, where Mild holds it: while the message is waiting on the user (and Mild would move it or
   * could not place it), or for good once the user has answered for it. Null otherwise. Its HTML is held with it.
   */
  body: held.nullable(),
  /** Whether Mild holds its HTML, beside the text, to show in a frame (`/api/message/html`). */
  hasHtml: z.boolean(),
  /** Its files, where Inbox keeps its text. Null when they were not kept with it: `/api/mail/attachments` reads them. */
  attachments: z.array(MessageAttachment).nullable(),
  facts: MessageFactSet,
  sender: SenderProfile,
  /**
   * Whether Mild could leave the list this message came from. `available`: yes, with one request to the sender.
   * `done`: it already has. `manual`: the message has an unsubscribe link Mild will not use (it needs an
   * email sent or a page opened, or the message did not prove who sent it). `none`: it offers no way.
   */
  unsubscribe: z.enum(['available', 'done', 'manual', 'none']),
  /** Set where the message is one of Mild's digests. */
  digest: DigestShown.nullable(),
  /** Every decision made about this message, oldest first. */
  decisions: z.array(
    DecisionRow.extend({
      ruleId: z.string().nullable(),
      inputTokens: z.number(),
      outputTokens: z.number(),
      durationMs: z.number().nullable(),
      /** What the user said this message is, where they answered for this decision; it beats the decision. */
      answer: z.object({ labelId: z.string().nullable(), disposition: z.string() }).nullable(),
    }),
  ),
  /** Every mailbox change made to this message, oldest first. */
  actions: z.array(
    z.object({
      id: z.number(),
      type: z.string(),
      status: z.string(),
      added: z.array(held),
      removed: z.array(held),
      createdAt: z.number(),
    }),
  ),
});
export type MessageDetail = z.infer<typeof MessageDetail>;

export const MessagesAhead = z.object({ messages: z.array(MessageDetail) });
export type MessagesAhead = z.infer<typeof MessagesAhead>;
