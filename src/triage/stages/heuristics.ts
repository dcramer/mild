import { type Facts, deriveFacts } from '../facts.ts';
import { type Label, type MessageFacts, type Stage, labelled } from '../types.ts';

export interface HeuristicsDeps {
  labels: readonly Label[];
  /** Whether the owner has ever written to the sender. Null: it could not be checked. Asked only for mail that is plainly bulk. */
  hasWritten: (message: MessageFacts) => Promise<boolean | null>;
}

/** Services that carry publications people subscribe to, not a company's campaigns. */
const NEWSLETTER_PLATFORMS = new Set(['Substack', 'beehiiv']);

/**
 * Which of the default bulk labels the headers point to, or null. Every sign has to agree: a mailing
 * list with a one-click unsubscribe, sent through a bulk mail service, from a sender who proved who they
 * are, and neither a reply nor marked as written by a program (which is how notifications look).
 * Marketing needs Gmail to have filed it under Promotions; Newsletters needs a newsletter platform and
 * Gmail not to disagree. Anything else, notifications included, is left for the next tier.
 */
function bulkLabel(facts: Facts): 'marketing' | 'newsletter' | null {
  const plainlyBulk =
    facts.unsubscribe === 'one-click' &&
    facts.listId !== null &&
    facts.bulkService !== null &&
    facts.dmarc === 'pass' &&
    !facts.isReply &&
    !facts.autoGenerated;
  if (!plainlyBulk) return null;
  const platform = NEWSLETTER_PLATFORMS.has(facts.bulkService ?? '');
  if (facts.category === 'promotions') return platform ? null : 'marketing';
  if (platform && (facts.category === null || facts.category === 'updates' || facts.category === 'forums')) return 'newsletter';
  return null;
}

/**
 * Names a label from the headers alone, before any model, for mail that is plainly bulk. It abstains
 * unless the owner is known never to have written to the sender, so it cannot hide mail from a correspondent.
 */
export function heuristicsStage(deps: HeuristicsDeps): Stage {
  return {
    name: 'heuristics',
    async decide(message) {
      const facts = deriveFacts(message);
      const id = bulkLabel(facts);
      const label = id && deps.labels.find((l) => l.id === id);
      if (!label) return null;
      if ((await deps.hasWritten(message)) !== false) return null;
      const category = facts.category === 'promotions' ? ', filed under Promotions by Gmail' : '';
      return {
        ...labelled(label),
        stage: 'heuristics',
        reason: `${label.name} by its headers: list ${facts.listId}, one-click unsubscribe, sent through ${facts.bulkService}${category}`,
      };
    },
  };
}
