/** `fail` is anything recorded that is not a pass (softfail, neutral, an error). `none`: the receiver recorded no result. */
type AuthResult = 'pass' | 'fail' | 'none';

/**
 * What only the whole message shows. It is read when a model is about to judge the message, so these are
 * absent until then, and the HTML ones stay absent for mail with no HTML part.
 */
export interface ContentFacts extends Partial<HtmlFacts> {
  /** A file came with it. Images shown inline in the text do not count. */
  hasAttachments: boolean;
  /** Words in all of its readable text, before the model's cut: how long it takes to read. Recorded for a later estimate of time saved; absent for mail recorded before. */
  words?: number;
}

/** What the rest of the thread shows. Looked up only for a reply, when a model is about to judge it. */
export interface ThreadFacts {
  /** Messages in the thread before this one. */
  earlierInThread: number;
  /** One of those earlier messages was sent by the owner. */
  ownerInThread: boolean;
}

/** `messages` is the thread oldest first; a message the owner sent carries Gmail's `SENT` label. Null if the message is not in it. */
export function threadFacts(messages: readonly { id: string; labelIds: readonly string[] }[], messageId: string): ThreadFacts | null {
  const index = messages.findIndex((m) => m.id === messageId);
  if (index === -1) return null;
  const earlier = messages.slice(0, index);
  return { earlierInThread: earlier.length, ownerInThread: earlier.some((m) => m.labelIds.includes('SENT')) };
}

/**
 * What is known about one message, by name. The prompt, the dashboard and rule conditions all read these instead of re-reading headers. Only what can be checked is here: whether
 * mail "reads as AI-generated" or what language it is in are judgements, and belong to a model.
 */
export interface Facts extends Partial<ContentFacts>, Partial<ThreadFacts> {
  /** `one-click` is RFC 8058, the only kind sift will use itself. */
  unsubscribe: 'none' | 'header' | 'one-click';
  listId: string | null;
  /** `Precedence: bulk`, `list` or `junk`. */
  markedBulk: boolean;
  /** `Auto-Submitted` says a program wrote it. */
  autoGenerated: boolean;
  dmarc: AuthResult;
  spf: AuthResult;
  dkim: AuthResult;
  /** The bulk mail service it was sent through, when its headers show one. Null does not mean it was sent by hand. */
  bulkService: string | null;
  /** Replies would go to an address other than the sender's. */
  replyToDiffers: boolean;
  /** Where the owner's address appears. `neither`: a list or a blind copy. */
  addressed: 'to' | 'cc' | 'neither';
  /** It answers an earlier message (`In-Reply-To` or `References`). */
  isReply: boolean;
  /**
   * Who sent it, beside the owner: one of their own addresses, or someone at their own domain (a
   * subdomain counts; a domain anyone can get an address at never does). Only DMARC says it is true.
   * Absent for mail recorded before sift read it.
   */
  origin?: 'owner' | 'own-domain' | 'outside';
  /** The inbox tab Gmail filed it under, from its `CATEGORY_*` label. Null: none recorded. */
  category: 'personal' | 'social' | 'promotions' | 'updates' | 'forums' | null;
  /**
   * Gmail's importance marker, as it stood when sift recorded the message. Gmail sets it from how the owner
   * treats mail like it, and the owner can set it by hand; the API does not say which. Absent for mail
   * recorded before sift read it.
   */
  important?: boolean;
}

