const under = (host: string, domain: string) => host === domain || host.endsWith(`.${domain}`);

function authResult(results: string, method: string): AuthResult {
  const found = [...results.matchAll(new RegExp(`\\b${method}=([a-z]+)`, 'gi'))].map((m) => m[1]!.toLowerCase());
  // A message can carry several DKIM signatures; one that verifies is enough.
  if (found.includes('pass')) return 'pass';
  return found.some((r) => r !== 'none') ? 'fail' : 'none';
}

/**
 * The domains that handled the message, as the receiver recorded them: who signed it (DKIM), and the
 * envelope sender (SPF, Return-Path). A service that sends on behalf of a customer shows up here even
 * when From is the customer's own address.
 */
function sendingDomains(headers: Record<string, string>): string[] {
  const results = headers['authentication-results'] ?? '';
  const domains = [...results.matchAll(/\b(?:header\.[id]|smtp\.mailfrom)=(?:[^\s;@]*@)?([a-z0-9.-]+)/gi)].map((m) => m[1]!.toLowerCase());
  const returnPath = parseAddress(headers['return-path'] ?? '');
  return returnPath ? [...domains, returnPath.domain] : domains;
}

function bulkService(headers: Record<string, string>): string | null {
  const domains = sendingDomains(headers);
  const mailer = headers['x-mailer'] ?? '';
  const feedbackId = headers['feedback-id'] ?? '';
  const service = SERVICES.find(
    (s) =>
      s.domains?.some((d) => domains.some((host) => under(host, d))) ||
      s.headers?.some((h) => headers[h] !== undefined) ||
      s.mailer?.test(mailer) ||
      s.feedbackId?.test(feedbackId),
  );
  return service?.name ?? null;
}

/** Gmail delivers `name+tag@` to `name@`, so mail to a tagged address was still addressed to the owner. */
const untagged = (address: string) => address.replace(/\+[^@]*@/, '@');

const CATEGORIES = {
  personal: 'CATEGORY_PERSONAL',
  social: 'CATEGORY_SOCIAL',
  promotions: 'CATEGORY_PROMOTIONS',
  updates: 'CATEGORY_UPDATES',
  forums: 'CATEGORY_FORUMS',
} as const;

/** The facts a message's headers and labels give. The account id is the owner's address. */
export function deriveFacts(
  message: Pick<MessageFacts, 'accountId' | 'from' | 'to' | 'cc' | 'labelIds' | 'headers'>,
  read: Partial<ContentFacts & ThreadFacts> = {},
): Facts {
  const { headers } = message;
  const signals = bulkSignals(headers);
  const results = headers['authentication-results'] ?? '';
  const owner = message.accountId.toLowerCase();
  const isOwner = (a: { address: string }) => untagged(a.address) === owner;
  const replyTo = parseAddressList(headers['reply-to']);
  const category = (Object.keys(CATEGORIES) as (keyof typeof CATEGORIES)[]).find((key) => message.labelIds.includes(CATEGORIES[key]));

  return {
    unsubscribe: signals.oneClickUnsubscribeUrl ? 'one-click' : signals.hasListUnsubscribe ? 'header' : 'none',
    listId: signals.listId,
    markedBulk: signals.precedenceBulk,
    autoGenerated: signals.autoSubmitted,
    dmarc: authResult(results, 'dmarc'),
    spf: authResult(results, 'spf'),
    dkim: authResult(results, 'dkim'),
    bulkService: bulkService(headers),
    replyToDiffers: replyTo.length > 0 && !replyTo.some((a) => a.address === message.from.address),
    addressed: message.to.some(isOwner) ? 'to' : message.cc.some(isOwner) ? 'cc' : 'neither',
    isReply: (headers['in-reply-to'] ?? headers['references'] ?? '').trim() !== '',
    category: category ?? null,
    ...read,
  };
}

const yesNo = (value: boolean) => (value ? 'yes' : 'no');

/** The facts as `name: value` lines, for the model. One that is not known has no line. */
export function describeFacts(facts: Facts): string[] {
  const addressed = { to: 'directly (To)', cc: 'by copy (Cc)', neither: 'no (a list or a blind copy)' }[facts.addressed];
  return [
    `Addressed to the owner: ${addressed}`,
    `Is a reply to an earlier message: ${yesNo(facts.isReply)}`,
    ...(facts.earlierInThread === undefined ? [] : [`Earlier messages in its thread: ${facts.earlierInThread}`]),
    ...(facts.ownerInThread === undefined ? [] : [`Owner has written in its thread: ${yesNo(facts.ownerInThread)}`]),
    `Mailing list id: ${facts.listId ?? '(none)'}`,
    `Unsubscribe header: ${{ none: 'no', header: 'yes', 'one-click': 'yes, one-click' }[facts.unsubscribe]}`,
    `Marked bulk: ${yesNo(facts.markedBulk)}`,
    `Marked auto-generated: ${yesNo(facts.autoGenerated)}`,
    `Sent through a bulk mail service: ${facts.bulkService ?? 'none recognised'}`,
    `Sender authentication: DMARC ${facts.dmarc}, SPF ${facts.spf}, DKIM ${facts.dkim}`,
    `Replies go to a different address: ${yesNo(facts.replyToDiffers)}`,
    `Gmail's category: ${facts.category ?? '(none)'}`,
    ...(facts.hasAttachments === undefined ? [] : [`Has attachments: ${yesNo(facts.hasAttachments)}`]),
    ...(facts.trackingPixel === undefined ? [] : [`Has a tracking pixel: ${yesNo(facts.trackingPixel)}`]),
    ...(facts.trackedLinks === undefined ? [] : [`Links pass through click tracking: ${yesNo(facts.trackedLinks)}`]),
    ...(facts.linkHosts === undefined ? [] : [`Distinct sites linked to: ${facts.linkHosts}`]),
    ...(facts.linksOffDomain === undefined
      ? []
      : [`Links go to the sender's own domain: ${facts.linkHosts === 0 ? '(no links)' : yesNo(!facts.linksOffDomain)}`]),
  ];
}

/**
 * Conditions on facts, for a rule ("has an unsubscribe header and is not a reply"). A value must equal
 * the fact, a list must contain it, and `true` or `false` against a fact that is a name or null
 * (`listId`, `bulkService`, `category`) asks whether there is one.
 */
export type FactConditions = {
  [K in keyof Facts]?: NonNullable<Facts[K]> | readonly NonNullable<Facts[K]>[] | (null extends Facts[K] ? boolean : never);
};

/** Every condition present must hold. No conditions never match, and a fact not known for the message fails its condition. */
export function matchesFacts(conditions: FactConditions, facts: Facts): boolean {
  const wanted = Object.entries(conditions).filter(([, want]) => want !== undefined);
  return (
    wanted.length > 0 &&
    wanted.every(([key, want]) => {
      const have: unknown = (facts as unknown as Record<string, unknown>)[key];
      if (have === undefined) return false;
      if (typeof want === 'boolean' && typeof have !== 'boolean') return (have !== null) === want;
      return Array.isArray(want) ? want.includes(have) : have === want;
    })
  );
}
