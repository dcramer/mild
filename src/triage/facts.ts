import type { MessageFacts } from './types.ts';

/** `fail` is anything recorded that is not a pass (softfail, neutral, an error). `none`: the receiver recorded no result. */
export type AuthResult = 'pass' | 'fail' | 'none';

/**
 * What is known about one message, by name. The prompt, the heuristics tier, the dashboard and rule
 * conditions all read these instead of re-reading headers. Only what can be checked is here: whether
 * mail "reads as AI-generated" or what language it is in are judgements, and belong to a model.
 */
export interface Facts {
  /** `one-click` is RFC 8058, the only kind sift will use itself. */
  unsubscribe: 'none' | 'header' | 'one-click';
  listId: string | null;
  /** `Precedence: bulk`, `list` or `junk`. */
  markedBulk: boolean;
  /** `Auto-Submitted` says a program wrote it. */
  autoGenerated: boolean;
  dmarc: AuthResult;
  spf: AuthResult;
  dkim: AuthResult;
  /** The bulk mail service it was sent through, when its headers show one. Null does not mean it was sent by hand. */
  bulkService: string | null;
  /** Replies would go to an address other than the sender's. */
  replyToDiffers: boolean;
  /** Where the owner's address appears. `neither`: a list or a blind copy. */
  addressed: 'to' | 'cc' | 'neither';
  /** It answers an earlier message (`In-Reply-To` or `References`). */
  isReply: boolean;
  /** The inbox tab Gmail filed it under, from its `CATEGORY_*` label. Null: none recorded. */
  category: 'personal' | 'social' | 'promotions' | 'updates' | 'forums' | null;
}

