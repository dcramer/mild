const under = (host: string, domain: string) => host === domain || host.endsWith(`.${domain}`);

function authResult(results: string, method: string): AuthResult {
  const found = [...results.matchAll(new RegExp(`\\b${method}=([a-z]+)`, 'gi'))].map((m) => m[1]!.toLowerCase());
  // A message can carry several DKIM signatures; one that verifies is enough.
  if (found.includes('pass')) return 'pass';
  return found.some((r) => r !== 'none') ? 'fail' : 'none';
}

/**
 * The domains that handled the message, as Gmail recorded them: who signed it (DKIM), and the
 * envelope sender (SPF, Return-Path). A service that sends on behalf of a customer shows up here even
 * when From is the customer's own address.
 */
function sendingDomains(headers: Record<string, string>): string[] {
  const results = receivedResults(headers);
  const domains = [...results.matchAll(/\b(?:header\.[id]|smtp\.mailfrom)=(?:[^\s;@]*@)?([a-z0-9.-]+)/gi)].map((m) => m[1]!.toLowerCase());
  const returnPath = parseAddress(headers['return-path'] ?? '');
  return returnPath ? [...domains, returnPath.domain] : domains;
}

function bulkService(headers: Record<string, string>): string | null {
  const domains = sendingDomains(headers);
  const mailer = headers['x-mailer'] ?? '';
  const feedbackId = headers['feedback-id'] ?? '';
  const service = SERVICES.find(
    (s) =>
      s.domains?.some((d) => domains.some((host) => under(host, d))) ||
      s.headers?.some((h) => headers[h] !== undefined) ||
      s.mailer?.test(mailer) ||
      s.feedbackId?.test(feedbackId),
  );
  return service?.name ?? null;
}

/**
 * An address as Gmail delivers it: `name+tag@` reaches `name@`, and on gmail.com, which googlemail.com is,
 * dots in the name are ignored. A Workspace domain's dots are significant, so only those two lose them.
 */
function canonical(address: string): string {
  const at = address.lastIndexOf('@');
  let local = address.slice(0, at).toLowerCase().replace(/\+.*$/, '');
  let domain = address.slice(at + 1).toLowerCase();
  if (domain === 'googlemail.com') domain = 'gmail.com';
  if (domain === 'gmail.com') local = local.replaceAll('.', '');
  return `${local}@${domain}`;
}

const CATEGORIES = {
  personal: 'CATEGORY_PERSONAL',
  social: 'CATEGORY_SOCIAL',
  promotions: 'CATEGORY_PROMOTIONS',
  updates: 'CATEGORY_UPDATES',
  forums: 'CATEGORY_FORUMS',
} as const;

/** The facts a message's headers and labels give. The owner is the account id and `aliases`, its other addresses in Gmail (send-as). */
export function deriveFacts(
  message: Pick<MessageFacts, 'accountId' | 'from' | 'to' | 'cc' | 'labelIds' | 'headers'>,
  read: Partial<ContentFacts & ThreadFacts> = {},
  aliases: readonly string[] = [],
): Facts {
  const { headers } = message;
  const signals = bulkSignals(headers);
  const results = receivedResults(headers);
  const owner = new Set([message.accountId, ...aliases].map(canonical));
  const isOwner = (a: { address: string }) => owner.has(canonical(a.address));
  const ownSites = new Set(
    [message.accountId, ...aliases]
      .map((a) => a.slice(a.lastIndexOf('@') + 1).toLowerCase())
      .filter((d) => d !== '' && !isSharedDomain(d))
      .map(site),
  );
  const replyTo = parseAddressList(headers['reply-to']);
  const category = (Object.keys(CATEGORIES) as (keyof typeof CATEGORIES)[]).find((key) => message.labelIds.includes(CATEGORIES[key]));

  return {
    unsubscribe: signals.oneClickUnsubscribeUrl ? 'one-click' : signals.hasListUnsubscribe ? 'header' : 'none',
    listId: signals.listId,
    markedBulk: signals.precedenceBulk,
    autoGenerated: signals.autoSubmitted,
    dmarc: authResult(results, 'dmarc'),
    spf: authResult(results, 'spf'),
    dkim: authResult(results, 'dkim'),
    bulkService: bulkService(headers),
    replyToDiffers: replyTo.length > 0 && !replyTo.some((a) => a.address === message.from.address),
    addressed: message.to.some(isOwner) ? 'to' : message.cc.some(isOwner) ? 'cc' : 'neither',
    isReply: (headers['in-reply-to'] ?? headers['references'] ?? '').trim() !== '',
    origin: isOwner(message.from) ? 'owner' : ownSites.has(site(message.from.domain)) ? 'own-domain' : 'outside',
    category: category ?? null,
    important: message.labelIds.includes('IMPORTANT'),
    ...read,
  };
}

const yesNo = (value: boolean) => (value ? 'yes' : 'no');

/**
 * What the model is told about a message: only what is there. Tracking and link facts are left out: they
 * repeat the bulk signals, and off-domain links read as phishing on any mail sent through click tracking.
 * Gmail's importance marker is left out until it is shown to be worth something (TODO.md).
 */
export function describeFacts(facts: Facts): string[] {
  const addressed = { to: 'directly (To)', cc: 'by copy (Cc)', neither: 'no (a list or a blind copy)' }[facts.addressed];
  const bulk = bulkMarks(facts);
  return [
    `Addressed to the owner: ${addressed}`,
    ...(facts.origin === 'owner' ? ["From one of the owner's own addresses"] : facts.origin === 'own-domain' ? ["From the owner's own domain"] : []),
    ...(facts.isReply ? ['A reply to an earlier message'] : []),
    ...(facts.earlierInThread === undefined ? [] : [`Earlier messages in its thread: ${facts.earlierInThread}`]),
    ...(facts.ownerInThread === undefined ? [] : [`Owner has written in its thread: ${yesNo(facts.ownerInThread)}`]),
    `Bulk signals: ${bulk.length === 0 ? 'none' : bulk.join(', ')}`,
    // DMARC is what proves the sender; SPF and DKIM only say why it did not.
    `Sender authentication: ${facts.dmarc === 'pass' ? 'DMARC pass' : `DMARC ${facts.dmarc}, SPF ${facts.spf}, DKIM ${facts.dkim}`}`,
    ...(facts.category === null ? [] : [`Gmail's category: ${facts.category}`]),
    ...(facts.hasAttachments ? ['Has attachments'] : []),
  ];
}

/** The signs that a message was sent to many, each named; the sender writes all of them. */
function bulkMarks(facts: Facts): string[] {
  return [
    ...(facts.unsubscribe === 'none' ? [] : [facts.unsubscribe === 'one-click' ? 'one-click unsubscribe' : 'unsubscribe header']),
    ...(facts.listId === null ? [] : [`list ${JSON.stringify(facts.listId)}`]),
    ...(facts.markedBulk ? ['marked bulk'] : []),
    ...(facts.autoGenerated ? ['auto-generated'] : []),
    ...(facts.bulkService === null ? [] : [`via ${facts.bulkService}`]),
  ];
}

/**
 * The facts that tell one kind of mail from another, on one line, naming only what is there. For an
 * example beside the message being judged, so the model can compare their headers as well as their text.
 */
export function factLine(facts: Facts): string {
  const bulk = bulkMarks(facts);
  return [
    ...(facts.category === null ? [] : [`Gmail ${facts.category}`]),
    ...(facts.origin === 'owner' ? ['from the owner'] : facts.origin === 'own-domain' ? ["from the owner's domain"] : []),
    { to: 'to the owner', cc: 'owner in Cc', neither: 'not addressed to the owner' }[facts.addressed],
    ...(facts.isReply ? ['a reply'] : []),
    ...(facts.ownerInThread ? ['owner wrote in its thread'] : []),
    `bulk: ${bulk.length === 0 ? 'none' : bulk.join(', ')}`,
    `DMARC ${facts.dmarc}`,
    ...(facts.hasAttachments ? ['attachments'] : []),
  ].join('; ');
}

/**
 * Conditions on facts, for a rule ("has an unsubscribe header and is not a reply"). A value must equal
 * the fact, a list must contain it, and `true` or `false` against a fact that is a name or null
 * (`listId`, `bulkService`, `category`) asks whether there is one.
 */
type FactConditions = {
  [K in keyof Facts]?: NonNullable<Facts[K]> | readonly NonNullable<Facts[K]>[] | (null extends Facts[K] ? boolean : never);
};

/**
 * The facts a rule can ask about, each with the answers it can want and how they read after "mail that".
 * An answer is a `matchesFacts` condition. Left out: counts, the list's own id (a rule matches that by
 * name), SPF and DKIM (DMARC is the one that proves the sender), and what only reads as a judgement.
 * "No tracking pixel" is not offered: mail with no HTML has no answer, and would never match it.
 */
export const RULE_FACTS = {
  unsubscribe: [
    ['one-click', 'has a one-click unsubscribe'],
    [['header', 'none'], 'has no one-click unsubscribe'],
  ],
  listId: [
    [true, 'came through a mailing list'],
    [false, 'did not come through a mailing list'],
  ],
  markedBulk: [
    [true, 'is marked bulk'],
    [false, 'is not marked bulk'],
  ],
  bulkService: [
    [true, 'was sent through a bulk mail service'],
    [false, 'was sent through no bulk mail service Sift knows'],
  ],
  dmarc: [
    ['pass', 'passed DMARC'],
    [['fail', 'none'], 'did not pass DMARC'],
  ],
  replyToDiffers: [
    [true, 'has replies going elsewhere'],
    [false, 'has replies going to the sender'],
  ],
  addressed: [
    ['to', 'is addressed to you'],
    ['cc', 'copies you'],
    ['neither', 'does not name you'],
  ],
  isReply: [
    [true, 'is a reply'],
    [false, 'is not a reply'],
  ],
  category: [
    ['personal', 'is in Primary'],
    ['promotions', 'is in Promotions'],
    ['social', 'is in Social'],
    ['updates', 'is in Updates'],
    ['forums', 'is in Forums'],
  ],
  important: [
    [true, 'Gmail marked important'],
    [false, 'Gmail did not mark important'],
  ],
  hasAttachments: [
    [true, 'has attachments'],
    [false, 'has no attachments'],
  ],
  trackingPixel: [[true, 'has a tracking pixel']],
} as const satisfies { [K in keyof Facts]?: readonly (readonly [FactConditions[K], string])[] };

type RuleFactKey = keyof typeof RULE_FACTS;
/** What a rule asks of a message's facts: for each fact it names, one of the answers in `RULE_FACTS`. */
export type RuleFacts = { [K in RuleFactKey]?: (typeof RULE_FACTS)[K][number][0] };

/** Only the whole message shows these, so a rule that asks about one needs it read first. */
export const CONTENT_FACTS = ['hasAttachments', 'trackingPixel'] as const satisfies readonly RuleFactKey[];

/** The same answer: a list holds the same values in any order. */
const same = (a: unknown, b: unknown) => (Array.isArray(a) && Array.isArray(b) ? a.length === b.length && a.every((v) => b.includes(v)) : a === b);

/** The words for one answer in `RULE_FACTS`, or null if the fact has no such answer. */
export function factCondition(key: string, want: unknown): string | null {
  const answers: readonly (readonly [unknown, string])[] | undefined = (RULE_FACTS as Record<string, readonly (readonly [unknown, string])[]>)[key];
  return answers?.find(([value]) => same(value, want))?.[1] ?? null;
}

/** Every condition present must hold. No conditions never match, and a fact not known for the message fails its condition. */
export function matchesFacts(conditions: FactConditions, facts: Facts): boolean {
  const wanted = Object.entries(conditions).filter(([, want]) => want !== undefined);
  return (
    wanted.length > 0 &&
    wanted.every(([key, want]) => {
      const have: unknown = (facts as unknown as Record<string, unknown>)[key];
      if (have === undefined) return false;
      if (typeof want === 'boolean' && typeof have !== 'boolean') return (have !== null) === want;
      return Array.isArray(want) ? want.includes(have) : have === want;
    })
  );
}
